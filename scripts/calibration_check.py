"""Are the summed log-likelihood ratios calibrated log-odds?

If a score Lambda is the true log-likelihood ratio between generators A and B, then with equal priors
P(A | Lambda) = sigmoid(Lambda). Three checks, for the base model (PHLE) and for the generator (real system prompts),
on the main comparisons, per answer and for bags of k = 10 / 30 matched answers (bags drawn as in make_tables.py):

  slope, intercept   logistic fit P(A | Lambda) = sigmoid(slope * Lambda + intercept); calibrated: 1, 0.
                     slope < 1 means the score overstates the evidence (it is too spread out for its separation).
  AUC vs implied     for a calibrated, Gaussian log-likelihood ratio, the class means are +-d/2 and each variance is d,
                     so the AUC follows from the mean separation d alone: AUC = Phi(sqrt(d / 2)).
  log E_B[e^Lambda]  should be 0 for a true likelihood ratio (and log E_A[e^-Lambda] likewise).

    python scripts/calibration_check.py      # -> results/calibration.md
"""
import numpy as np
from scipy.stats import norm
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score

src = open("scripts/make_tables.py").read(); g = {"__name__": "mt"}
exec(src[:src.index("# ---------------------------------------------------------------- tables")], g)
load, raw_by_question, F = g["load"], g["raw_by_question"], g["F"]

COMPS = [  # (label, base key, generator key, pos, neg, header a, header b, modality)
    ("owl vs no prompt (text)", "olmo_base_text", "olmo_inst_text", "owl", "control", "owl", "neutral", "text"),
    ("owl vs trains (text)", "olmo_base_text", "olmo_inst_text", "owl", "trains", "owl", "trains", "text"),
    ("owl vs no prompt (numbers)", "olmo_base_num18", "olmo_inst_num18", "owl", "control", "owl", "neutral", "numbers"),
    ("owl vs trains (numbers)", "olmo_base_num18", "olmo_inst_num18", "owl", "trains", "owl", "trains", "numbers"),
    ("owl vs eagle (text)", "olmo_base_eagle", "olmo_inst_eagle", "owl", "eagle", "owl", "eagle", "text"),
    ("owl vs eagle (numbers)", "olmo_base_eagleN", "olmo_inst_eagleN", "owl", "eagle", "owl", "eagle", "numbers"),
    ("secret harm vs no prompt (text)", "olmo_base_text11", "olmo_inst_text11", "af", "control", "af", "neutral", "text"),
    ("secret harm vs secret friend (text)", "olmo_base_text11", "olmo_inst_text11", "af", "af_friend", "af", "af_friend", "text"),
]
N_BAGS = 4000

def bags(byq, pos, neg, k, rng):
    qs = sorted(byq); P, N = [], []
    for _ in range(N_BAGS):
        qq = rng.choice(len(qs), min(k, len(qs)), replace=False)
        P.append(sum(byq[qs[j]][pos][0][rng.integers(len(byq[qs[j]][pos][0])), 0] for j in qq))
        N.append(sum(byq[qs[j]][neg][0][rng.integers(len(byq[qs[j]][neg][0])), 0] for j in qq))
    return np.array(P), np.array(N)

def stats(P, N):
    x = np.r_[P, N]; y = np.r_[np.ones(len(P)), np.zeros(len(N))]
    lr = LogisticRegression(C=1e6).fit(x[:, None], y)
    d = P.mean() - N.mean(); implied = norm.cdf(np.sqrt(d / 2)) if d > 0 else float("nan")
    lse = lambda v: np.log(np.mean(np.exp(v - v.max()))) + v.max()
    return dict(auc=roc_auc_score(y, x), implied=implied, slope=lr.coef_[0, 0], icpt=lr.intercept_[0], d=d,
                sdA=P.std(), sdB=N.std(), eB=lse(N), eA=lse(-P))

rows = []
for lab, kb, ki, pos, neg, a, b, mod in COMPS:
    for who, key in [("base PHLE", kb), ("generator", ki)]:
        byq = raw_by_question(load(F[key], mod), pos, neg, [(a, b)]); rng = np.random.default_rng(0)
        P1 = np.concatenate([byq[q][pos][0][:, 0] for q in byq]); N1 = np.concatenate([byq[q][neg][0][:, 0] for q in byq])
        res = {"k=1": stats(P1, N1)}
        for k in (10, 30): res[f"k={k}"] = stats(*bags(byq, pos, neg, k, rng))
        rows.append((lab, who, res))

out = ["# Calibration of the summed log-likelihood ratios (Olmo)\n",
       "Generated by `scripts/calibration_check.py`. For each comparison and k: AUC; the AUC a calibrated Gaussian log-likelihood ratio with the same mean "
       "separation would have, Phi(sqrt(d/2)); the logistic calibration slope and intercept (calibrated: 1 and 0); the mean separation d and the "
       "class standard deviations (nats); and log E_B[e^Lambda] / log E_A[e^-Lambda] (0 for a true likelihood ratio). Per-answer values use every "
       "matched answer; k = 10 / 30 use 4,000 bags of matched questions.\n"]
for k in ["k=1", "k=10", "k=30"]:
    out.append(f"\n## {k}\n\n| comparison | scorer | AUC | implied AUC | slope | intercept | d | sd A | sd B | log E_B[e^Λ] | log E_A[e^-Λ] |\n|---|---|---|---|---|---|---|---|---|---|---|")
    for lab, who, res in rows:
        r = res[k]; out.append(f"| {lab} | {who} | {r['auc']:.2f} | {r['implied']:.2f} | {r['slope']:.2f} | {r['icpt']:+.2f} | {r['d']:.2f} | {r['sdA']:.2f} | {r['sdB']:.2f} | {r['eB']:+.2f} | {r['eA']:+.2f} |")
open("results/calibration.md", "w").write("\n".join(out) + "\n"); print("\n".join(out))
