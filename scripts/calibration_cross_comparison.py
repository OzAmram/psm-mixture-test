"""Does a PHLE calibration fitted on one comparison transfer to a different comparison (same model family)?

For every pair (calibration comparison X, test comparison Y) of the eight Olmo comparisons: fit the per-answer slope and
offset on all of X's answers (Olmo base scorer, Olmo generators), apply it to Y's answers (a * Lambda_k + k * b for
k-answer sums), and report Y's balanced log-loss (0.693 = no information) and the calibration slope of the corrected
score on Y (calibrated: 1). Diagonal = calibrating on the test comparison itself (the best possible).
Helpers (fit, logloss, per_answer, bags, COMPS) come from scripts/calibration_transfer.py.

    python scripts/calibration_cross_comparison.py      # -> results/calibration_cross_comparison.md
"""
import numpy as np

src = open("scripts/calibration_transfer.py").read(); g = {"__name__": "ct"}
exec(src[:src.index("rows = []")], g)
fit, logloss, per_answer, bags, COMPS, K = g["fit"], g["logloss"], g["per_answer"], g["bags"], g["COMPS"], g["K"]
load, raw_by_question, F = g["load"], g["raw_by_question"], g["F"]

SHORT = ["owl/none text", "owl/trains text", "owl/none num", "owl/trains num", "owl/eagle text", "owl/eagle num", "harm/none text", "harm/friend text"]
data = []
for lab, key, pos, neg, a, b, mod in COMPS:
    byq = raw_by_question(load(F[key], mod), pos, neg, [(a, b)]); qs = sorted(byq)
    data.append(dict(one=per_answer(byq, qs, pos, neg), bag=bags(byq, qs, pos, neg, np.random.default_rng(0))))
cals = [fit(*d["one"]) for d in data]

out = ["# Calibration transfer across comparisons (Olmo base PHLE)\n", "Generated by `scripts/calibration_cross_comparison.py`. Rows: comparison the "
       "per-answer correction is fitted on; columns: comparison it is applied to. Each cell: balanced log-loss on the column comparison, then the calibration "
       "slope of the corrected score on it (1 = calibrated, >1 underconfident, <1 overconfident). The `raw` row reads the PHLE score directly as log-odds; "
       "the diagonal is the best possible.\n", "Fitted per-answer corrections (slope, offset): " + ", ".join(f"{s} ({a:.2f}, {b:+.2f})" for s, (a, b) in zip(SHORT, cals)) + "\n"]
for k, kind in [(1, "one"), (K, "bag")]:
    out.append(f"\n## {'per answer' if k == 1 else f'k = {K}'}\n\n| calibrated on \\ applied to | " + " | ".join(SHORT) + " |\n|---|" + "---|" * len(SHORT))
    raw = [f"{logloss(*d[kind]):.2f}" for d in data]; out.append("| raw | " + " | ".join(raw) + " |")
    for i, (a, b) in enumerate(cals):
        cells = []
        for d in data:
            P, N = d[kind]; Pc, Nc = a * P + k * b, a * N + k * b
            cells.append(f"{logloss(Pc, Nc):.2f} ({fit(Pc, Nc)[0]:.1f})")
        out.append(f"| {SHORT[i]} | " + " | ".join(cells) + " |")
open("results/calibration_cross_comparison.md", "w").write("\n".join(out) + "\n"); print("\n".join(out))
